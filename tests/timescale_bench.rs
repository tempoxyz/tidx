//! Seeded query benchmark: stock Postgres vs TimescaleDB columnstore cold tier.
//!
//! Seeds identical deterministic synthetic chain data (skewed address /
//! selector distributions, unique random hashes) into a stock Postgres and
//! a TimescaleDB server through the production write path, compresses all
//! chunks behind the hot window on the Timescale side, then measures the
//! serving query shapes on both.
//!
//! Run with:
//!   docker compose -f docker/local/docker-compose.yml up -d postgres timescaledb
//!   BENCH_BLOCKS=250000 cargo test --release --test timescale_bench -- --ignored --nocapture
//!
//! Env knobs:
//!   BENCH_BLOCKS          total blocks to seed (default 100,000)
//!   BENCH_TXS_PER_BLOCK   txs per block        (default 8)
//!   BENCH_LOGS_PER_BLOCK  logs per block       (default 16)
//!   STOCK_DATABASE_URL    default postgresql://tidx:tidx@localhost:5433/tidx
//!   TIMESCALE_DATABASE_URL default postgresql://tidx:tidx@localhost:5434/tidx

